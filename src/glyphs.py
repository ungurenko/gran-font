"""
Gran: glyph skeletons.

Every glyph is a set of centre-line strokes. build.py turns each stroke into a filled
outline with a constant stroke width (zero contrast), flat ends and mitred corners.

Units: 1000 per em. Cap height 700, x-height 520, ascender 720, descender -170.
A stroke is a list of points (x, y) or (x, y, c). The third value c cuts that corner with a
straight 45-degree facet of length c on both sides. That facet is the signature of the face.
Closed shapes start in the middle of an edge so that the seam disappears in the union.
"""

SW = 100          # default stroke width
CAP = 700
XH = 520
ASC = 720
DESC = -170

GLYPHS = {}       # char -> dict(W, strokes, clip, sb, sw)
ALIASES = {}      # char -> char whose outline is reused (different code point, same shape)


def stroke(pts, sw=None, clip=None):
    return {"pts": pts, "sw": sw, "clip": clip}


def box(x0, y0, x1, y1, c=0):
    """Closed chamfered rectangle (centre-line), seam in the middle of the top edge."""
    xm = (x0 + x1) / 2
    return [(xm, y1), (x1, y1, c), (x1, y0, c), (x0, y0, c), (x0, y1, c), (xm, y1)]


def add(ch, W, strokes, clip=(0, CAP), sb=(65, 65), sw=SW):
    GLYPHS[ch] = {"W": W, "strokes": strokes, "clip": clip, "sb": sb, "sw": sw}


def alias(ch, src):
    ALIASES[ch] = src


